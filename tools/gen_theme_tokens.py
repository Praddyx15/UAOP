#!/usr/bin/env python3
"""Regenerate the colour block of the GCS Theme.qml from SUITE_TOKENS.json.

SUITE_TOKENS.json is shared with FlightMD and AeroAtlas (STYLE_GUIDE.md §9), so
the hex values are never typed into QML by hand. Only the lines between the
BEGIN/END markers are rewritten; everything else in Theme.qml stays as written.

    python tools/gen_theme_tokens.py          # rewrite Theme.qml
    python tools/gen_theme_tokens.py --check  # exit 1 if it is out of date (CI)
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOKENS = REPO / "docs" / "04_UI_Architecture" / "SUITE_TOKENS.json"
THEME = REPO / "frontend" / "qt-desktop-gcs" / "ui" / "styles" / "Theme.qml"

BEGIN = "    // BEGIN generated by tools/gen_theme_tokens.py from SUITE_TOKENS.json (dark) -- do not edit"
END = "    // END generated"

# token -> QML property; `accent` is taken by the legacy alias at the bottom of Theme.qml
PROPS = {"accent": "accentColor"}

NOTES = {
    "bg0": "window ground",
    "bg1": "panel surfaces",
    "bg2": "cards, wells, inputs",
    "stroke": "borders, dividers, grid",
    "fg0": "primary text/values",
    "fg1": "labels, units",
    "fg2": "disabled, hints",
    "accent": "focus/selection only",
    "warnRed": "fills, armed strip, map marks",
    "warnRedText": "alert text, 7:1 on bg0-bg2",
    "simViolet": "sim/replay watermark, exclusive",
}


def render(tokens: dict) -> list[str]:
    dark = tokens["themes"]["dark"]
    lines = [BEGIN]
    for key, value in dark.items():
        prop = PROPS.get(key, key)
        line = f'    readonly property color {prop}: "{value}"'
        if key in NOTES:
            line = f"{line.ljust(52)}// {NOTES[key]}"
        lines.append(line)
    lines.append(f"    readonly property int radius: {int(tokens['radius']['gcs'])}")
    lines.append(END)
    return lines


def main() -> int:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    current = THEME.read_text(encoding="utf-8").split("\n")
    try:
        start = current.index(BEGIN)
        stop = current.index(END, start)
    except ValueError:
        print(f"{THEME.relative_to(REPO)}: generated-block markers not found")
        return 1

    updated = current[:start] + render(tokens) + current[stop + 1:]
    if updated == current:
        return 0
    if "--check" in sys.argv[1:]:
        print(f"{THEME.relative_to(REPO)} is out of date: run tools/gen_theme_tokens.py")
        return 1
    tmp = THEME.with_suffix(".qml.tmp")
    tmp.write_bytes("\n".join(updated).encode("utf-8"))
    tmp.replace(THEME)
    print(f"wrote {THEME.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
